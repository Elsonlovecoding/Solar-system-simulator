// ============================================================================
//  build-standalone.mjs — produces dist/orrery.bundle.js, a single classic
//  script containing the whole app (Three.js included) with solar.conf
//  embedded as text.
//
//  Why it exists: browsers refuse to load ES modules or fetch() data files
//  from file://, so double-clicking index.html can't use the modular source.
//  index.html detects file:// and loads this bundle instead — classic
//  scripts are allowed from disk — so the app works with zero setup.
//
//  The bundle is committed to the repo; rebuild it after changing any source
//  file or solar.conf:   npm install && npm run build
// ============================================================================

import { build } from 'esbuild';
import { readFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const conf_text = readFileSync(resolve(root, 'solar.conf'), 'utf8');

await build({
  stdin: {
    contents: `import './main.js';\n`,
    resolveDir: root,
    sourcefile: 'standalone-entry.js',
  },
  bundle: true,
  format: 'iife',
  minify: true,
  // Resolve the bare specifiers the import map handles in the browser.
  // Longest prefix wins, so addons resolve before the bare 'three'.
  alias: {
    'three/addons': resolve(root, 'lib/three/addons'),
    three: resolve(root, 'lib/three.module.js'),
  },
  outfile: resolve(root, 'dist/orrery.bundle.js'),
  banner: {
    // The conf assignment lives in the banner — plain script text prepended
    // BEFORE the module body — because an `import './main.js'` inside the
    // entry is hoisted above any statement next to it, and the app would
    // boot before the embedded conf existed.
    js:
      '/* Orrery standalone bundle — generated by scripts/build-standalone.mjs.\n' +
      ' * Do not edit; edit the files in src/ and rebuild with `npm run build`.\n' +
      ' * Includes Three.js r160 (MIT License, https://threejs.org). */\n' +
      `window.__SOLAR_CONF__ = ${JSON.stringify(conf_text)};`,
  },
  logLevel: 'info',
});
